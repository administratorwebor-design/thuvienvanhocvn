import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { startTestServer } from '../tests/support.mjs';
import { seedAssessments } from './seed-assessments.mjs';
const s=await startTestServer({seed:false});
let browser;
try {
  seedAssessments(s.env.DATA_DIR);
  await s.request('POST','/auth/register',{username:'browser-student',email:'browser@example.test',password:'Student!2026'});
  browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('dialog',d=>d.accept());
  await page.goto(s.base+'/login');
  await page.locator('input').first().fill('browser-student');
  await page.locator('input[type=password]').fill('Student!2026');
  await page.locator('button[type=submit]').click();await page.waitForURL(s.base+'/');
  await page.goto(s.base+'/quizzes');await page.waitForLoadState('networkidle');
  assert.equal((await s.request('GET','/quizzes')).data.quizzes.length,20);
  assert.equal((await s.request('GET','/categories?for=quizzes')).data.categories.length,7);
  fs.mkdirSync('artifacts/assessments',{recursive:true});
  await page.screenshot({path:'artifacts/assessments/list.png',fullPage:true});
  await page.goto(s.base+'/quiz/assessment-bat-nat');
  await page.getByRole('button',{name:/Bắt đầu/}).click();
  await page.locator('details summary').getByText('Ngữ liệu và yêu cầu của đề').waitFor();
  assert.equal(await page.locator('input[type=radio]').count(),32);
  assert.equal(await page.locator('textarea').count(),2);
  assert.ok(await page.locator('details').innerText());
  await page.screenshot({path:'artifacts/assessments/paper.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'artifacts/assessments/mobile.png',fullPage:true});
  const radios=page.locator('input[type=radio]');
  for(let i=0;i<8;i++)await radios.nth(i*4).check();
  for(let i=0;i<2;i++)await page.locator('textarea').nth(i).fill('Em cần tôn trọng và giúp đỡ bạn, không bắt nạt người khác.');
  await page.getByRole('button',{name:/Nộp bài/}).click();
  await page.getByText('Đã nộp bài!',{exact:true}).waitFor();
  await page.screenshot({path:'artifacts/assessments/result.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('PASS 20 papers, seven filters, student start, reading passage, 8 MC + 2 essays, mobile layout, submission, no browser errors');
}finally{await browser?.close();await s.stop();}
